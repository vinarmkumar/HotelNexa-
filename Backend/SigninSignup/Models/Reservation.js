const mongoose = require("mongoose");

const reservationSchema = new mongoose.Schema({
  userId: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, index: true },
  hotelId: { type: String, required: true, trim: true, maxlength: 200 },
  roomId: { type: mongoose.Schema.Types.ObjectId, ref: "Room", default: null, index: true },
  roomTypeId: { type: mongoose.Schema.Types.ObjectId, ref: "RoomType", default: null, index: true },
  bedCount: { type: Number, required: true, min: 1, max: 4 },
  adults: { type: Number, required: true, min: 1, max: 20 },
  childAges: { type: [Number], default: [] },
  checkIn: { type: Date, required: true },
  checkOut: { type: Date, required: true },
  nights: { type: Number, required: true, min: 1, max: 30 },
  nightlyRate: { type: Number, required: true, min: 1 },
  amount: { type: Number, required: true, min: 1 },
  paymentType: { type: String, enum: ["Full", "Advance"], default: "Full", required: true },
  amountDueNow: { type: Number, required: true, min: 1 },
  amountPaid: { type: Number, default: 0, min: 0 },
  balanceDue: { type: Number, required: true, min: 0 },
  balanceOrderId: { type: String, default: "" },
  balanceTransactionId: { type: String, default: "" },
  currency: { type: String, enum: ["INR"], default: "INR", required: true },
  paymentStatus: { type: String, enum: ["Pending", "Success", "Failed"], default: "Pending", required: true },
  status: { type: String, enum: ["PaymentPending", "Confirmed", "CheckedIn", "CheckedOut", "CancellationPending", "PaymentFailed", "Cancelled"], default: "PaymentPending", required: true },
  orderId: { type: String, required: true, unique: true },
  transactionId: { type: String, default: "" },
  refundId: { type: String, default: "" },
  refundStatus: { type: String, enum: ["NotStarted", "Pending", "Processed", "Failed"], default: "NotStarted" },
  refundedAt: { type: Date, default: null },
  cancellationRequestedAt: { type: Date, default: null },
  cancelledAt: { type: Date, default: null },
  checkedInAt: { type: Date, default: null },
  checkedOutAt: { type: Date, default: null },
  stayStatusUpdatedBy: { type: mongoose.Schema.Types.ObjectId, ref: "User", default: null },
  cancellationInitiatedBy: { type: String, enum: ["guest", "hotelAdmin", ""], default: "" },
  cancellationActorId: { type: mongoose.Schema.Types.ObjectId, default: null },
  cancellationActorName: { type: String, default: "", trim: true, maxlength: 80 },
  cancellationActorEmail: { type: String, default: "", trim: true, maxlength: 254 },
  cancellationReason: { type: String, default: "", trim: true, maxlength: 240 },
  refundClaimedAt: { type: Date, default: null, select: false },
  paymentVerifiedAt: { type: Date, default: null },
  confirmationEmailClaimedAt: { type: Date, default: null, select: false },
  confirmationEmailSentAt: { type: Date, default: null },
  confirmationEmailLastError: { type: String, default: "", select: false },
  cancellationEmailClaimedAt: { type: Date, default: null, select: false },
  cancellationEmailSentAt: { type: Date, default: null },
  cancellationEmailLastError: { type: String, default: "", select: false },
  holdExpiresAt: { type: Date, required: true },
}, { timestamps: true });

reservationSchema.index({ userId: 1, createdAt: -1 });
reservationSchema.index({ paymentStatus: 1, status: 1 });

module.exports = mongoose.models.Reservation || mongoose.model("Reservation", reservationSchema);
